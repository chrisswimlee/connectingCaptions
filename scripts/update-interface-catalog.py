#!/usr/bin/env python3
"""Generate the allowlist of app-owned UI copy; never register runtime user text."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / 'Sources/ConnectingCaptions'
CORE_SOURCES = ROOT / 'Sources/ConnectingCaptionsCore'
DESTINATION = SOURCES / 'Services/LiveTranslation/AppInterfaceCatalog.swift'
PATTERN = re.compile(r'(?:\bApp(?:Text|Button|Label|Toggle)\(|\bAppLanguage\.(?:text|format)\()\s*("(?:[^"\\]|\\.)*")')
COPY_FILES = {'TheaterReadiness.swift', 'TheaterEngineCopy.swift', 'TheaterStatus.swift', 'TheaterChromeHelp.swift'}
COPY_LITERAL = re.compile(r'"(?:[^"\\]|\\.)*"')


def catalog():
    keys = set()
    source_trees = [SOURCES]
    if CORE_SOURCES.exists():
        source_trees.append(CORE_SOURCES)
    for path in (p for tree in source_trees for p in tree.rglob('*.swift')):
        if path == DESTINATION:
            continue
        for match in PATTERN.finditer(path.read_text()):
            literal = re.sub(r'\\u\{([0-9a-fA-F]+)\}', lambda m: chr(int(m[1], 16)), match[1])
            if '\\(' in literal:
                raise ValueError(f'{path}: use numbered placeholders for interpolated UI text')
            key = json.loads(literal)
            if key:
                keys.add(key)
        # Shared immutable copy is also passed to AppText by name. Keep those
        # constants in the allowlist without admitting arbitrary runtime text.
        if path.name in COPY_FILES:
            for match in COPY_LITERAL.finditer(path.read_text()):
                literal = match[0]
                if '\\(' in literal:
                    continue
                key = json.loads(literal)
                if key and (key[0].isupper() or ' ' in key) and not key.startswith('Control-'):
                    keys.add(key)
    lines = ['// Generated by scripts/update-interface-catalog.py. Do not edit by hand.',
             'import Foundation', '', 'nonisolated enum AppInterfaceCatalog {',
             '    static let strings: Set<String> = [']
    lines += ['        ' + json.dumps(key, ensure_ascii=False) + ',' for key in sorted(keys)]
    return '\n'.join(lines + ['    ]', '}', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = catalog()
    if args.check:
        if not DESTINATION.exists() or DESTINATION.read_text() != expected:
            parser.exit(1, 'Interface catalog is stale. Run python3 scripts/update-interface-catalog.py\n')
    else:
        DESTINATION.write_text(expected)
    print(f'Interface catalog: {expected.count(chr(10)) - 7} strings; OK')


if __name__ == '__main__':
    main()
