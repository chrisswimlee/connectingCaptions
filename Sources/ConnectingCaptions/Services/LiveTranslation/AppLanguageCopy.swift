import Foundation

/// Wizard chrome in the setup languages. English is the fallback.
enum AppLanguageCopy {
    static func translation(languageID: String, english: String) -> String? {
        guard let key = Self.key(for: english) else { return nil }
        return Self.tables[languageID]?[key]
    }

    private static func key(for english: String) -> String? {
        switch english {
        case "Setup Wizard": return "wizardTitle"
        case "Welcome": return "welcome"
        case "Languages": return "languages"
        case "Captions": return "captions"
        case "Audience": return "audience"
        case "Ready": return "ready"
        case "A preview of the caption the room sees.": return "subWelcome"
        case "App language is the language this app uses. I speak is what you say. Show as is the caption.":
            return "subLanguages"
        case "Choose whether the original language sits under each sentence.": return "subCaptions"
        case "Who sees the caption in a screenshot or a call.": return "subAudience"
        case "Finish here, or open Theater and press Listen.": return "subReady"
        case "Set up Theater": return "welcomeTitle"
        case "Each sentence appears when it is ready.": return "welcomeBody"
        case "The original language can sit under each sentence.": return "welcomeSpoken"
        case "Each sentence appears when it is ready. Nothing shows while it is still being heard.":
            return "captionsBody"
        case "Accent color": return "accentTitle"
        case "Caption gold is the default. It tints buttons in this app.": return "accentDetail"
        case "Skip for now": return "skip"
        case "Back": return "back"
        case "Continue": return "continue"
        case "Finish": return "finish"
        case "Open Theater": return "openTheater"
        case "App language": return "appLanguage"
        case "The language this app uses.": return "appLanguageDetail"
        case "Mode": return "mode"
        case "I speak": return "iSpeak"
        case "Show as": return "showAs"
        case "Share slides": return "shareSlides"
        case "Step %d of %d · %@": return "stepFormat"
        case "Same language": return "sameLanguage"
        case "Theater mode": return "theaterMode"
        case "Swap languages": return "swapLanguages"
        case "Either way": return "eitherWay"
        case TheaterReadiness.screenShare: return "screenShare"
        default: return nil
        }
    }

